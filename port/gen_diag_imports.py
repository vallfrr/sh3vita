for value in PE(args.exe).imports().values():
    dll, name = value.split("!", 1)
    if name.startswith("#"):
        name = "ord" + name[1:]
    symbol = "imp_" + dll.split(".")[0] + "_" + re.sub(r"[^A-Za-z0-9_]", "_", name)
    if symbol in names and names[symbol] != value:
        raise SystemExit(f"symbol collision: {symbol}")
    names[symbol] = value
with args.output.open("w") as out:
    out.write('#include "x86rt.h"\n#include <stdio.h>\n#include <stdlib.h>\n')
    for symbol, value in sorted(names.items()):
        if symbol in implemented:
            continue  # diagnostic implementation in diag_runtime.c
        out.write(f'void {symbol}(CPU *c) {{ (void)c; fprintf(stderr, "[diag] import {value} not implemented\\n"); exit(30); }}\n')
print(f"{len(names) - len(implemented & names.keys())} fail-closed import stubs -> {args.output}")
